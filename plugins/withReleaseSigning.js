/**
 * Signs release builds with a private keystore instead of React Native's public debug key, which
 * anyone can use to sign an "update" that would install over this app and inherit its data.
 *
 * The keystore and its passwords never enter the repo: they are read from Gradle properties,
 * normally ~/.gradle/gradle.properties (see docs/windows-handoff.md). Without them a debug build
 * still builds from a fresh clone, but a release build fails (release audit F-03): it used to fall
 * back to the public debug key without a word. `-PTRAVEL_ORGANIZER_ALLOW_DEBUG_SIGNING` allows that
 * for a throwaway build that is never installed over the real app.
 *
 * A config plugin because android/ is regenerated by prebuild — a hand edit would not survive.
 */
const { withAppBuildGradle } = require('expo/config-plugins');

const MARKER = 'TRAVEL_ORGANIZER_STORE_FILE';

const SIGNING_CONFIG = `
        release {
            if (project.hasProperty('${MARKER}')) {
                storeFile file(project.property('${MARKER}'))
                storePassword project.property('TRAVEL_ORGANIZER_STORE_PASSWORD')
                keyAlias project.property('TRAVEL_ORGANIZER_KEY_ALIAS')
                keyPassword project.property('TRAVEL_ORGANIZER_KEY_PASSWORD')
            }
        }`;

// Checked when Gradle knows which tasks will run: a release package or bundle without the keystore
// stops the build, rather than coming out signed with the debug key.
const RELEASE_GUARD = `

gradle.taskGraph.whenReady { graph ->
    def signsRelease = graph.allTasks.any { task ->
        task.project == project && task.name in ['packageRelease', 'packageReleaseBundle', 'signReleaseBundle']
    }
    if (signsRelease && !project.hasProperty('${MARKER}') && !project.hasProperty('TRAVEL_ORGANIZER_ALLOW_DEBUG_SIGNING')) {
        throw new GradleException(
            "Release signing: ${MARKER} is not set, so this build would be signed with the public debug key. " +
            "Set the release keystore properties (docs/windows-handoff.md), or pass " +
            "-PTRAVEL_ORGANIZER_ALLOW_DEBUG_SIGNING for a throwaway build."
        )
    }
}
`;

function applySigning(gradle) {
  if (gradle.includes(MARKER)) return gradle;

  const signingConfigs = /signingConfigs \{\n(\s+)debug \{[\s\S]*?\n\1\}/;
  if (!signingConfigs.test(gradle)) throw new Error('withReleaseSigning: signingConfigs block not found');
  let next = gradle.replace(signingConfigs, (block) => block + SIGNING_CONFIG);

  const releaseUsesDebug =
    /(release \{\n(?:\s*\/\/.*\n)*\s*)signingConfig signingConfigs\.debug/;
  if (!releaseUsesDebug.test(next)) throw new Error('withReleaseSigning: release signingConfig not found');
  next = next.replace(
    releaseUsesDebug,
    `$1signingConfig project.hasProperty('${MARKER}') ? signingConfigs.release : signingConfigs.debug`,
  );
  return next + RELEASE_GUARD;
}

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    cfg.modResults.contents = applySigning(cfg.modResults.contents);
    return cfg;
  });
};

module.exports.applySigning = applySigning;
